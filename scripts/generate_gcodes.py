#!/usr/bin/env python3
# pyright: strict
"""Update the G-codes the console offers, and what each does, from MonacoTokens.

MonacoTokens (https://github.com/Duet3D/MonacoTokens) is the G-code dictionary Duet Web Control's editor
uses: every code RepRapFirmware understands, with a one-line summary. From it this writes:

  - the table of codes in src/UI/Presenters/Console/Gcodes.cpp, in the dictionary's order, less the
    deprecated codes, each with the translation key of its summary (gcodes.gcode_<code>_desc, a . in
    the code written as _);
  - the gcodes block of every translation file in assets/i18n: the English summary of each code, except
    where a language has its own translation, which is kept.

    scripts/generate_gcodes.py                  from the pinned release
    scripts/generate_gcodes.py --ref v3.7-dev   from a branch, tag or commit
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.request
from collections.abc import Sequence
from dataclasses import dataclass
from typing import cast

from common import jsonc
from common.project import ROOT, complete

DEFAULT_REF = 'v3.7.0'
"""The MonacoTokens release the codes are taken from."""

URL = 'https://raw.githubusercontent.com/Duet3D/MonacoTokens/{ref}/src/gcodes/gcodes.json'
"""Where the dictionary is downloaded from."""

TABLE = ROOT / 'src' / 'UI' / 'Presenters' / 'Console' / 'Gcodes.cpp'
"""The source file whose table lists the codes."""

TABLE_RE = re.compile(r'(?P<start>\t: m_gcodes\(\{\n)(?P<rows>.*?)(?P<end>\t  \}\))', re.DOTALL)
"""The table's rows, in the constructor's member initialiser."""

BLOCK_RE = re.compile(r'(?P<start>\n(?P<indent> *)"gcodes": \{[^\n]*\n)(?P<entries>.*?)(?P<end>\n(?P=indent)\})', re.DOTALL)
"""The gcodes block of a translation file, which holds one "key": "summary" line per code."""

SECTION = 'gcodes'
"""The translation section the summaries are in."""


@dataclass(frozen=True)
class Gcode:
    """A code the console offers."""
    code: str
    summary: str

    @property
    def key(self) -> str:
        """The translation key of its summary, within the gcodes section."""
        return f'gcode_{self.code.replace(".", "_")}_desc'


@dataclass(frozen=True)
class Options:
    """The command line, typed."""
    ref: str


def parse_options(argv: Sequence[str]) -> Options:
    """Read the command line."""
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--ref', default=DEFAULT_REF,
                        help=f'the MonacoTokens branch, tag or commit (default: {DEFAULT_REF})')
    complete(parser)
    return Options(**vars(parser.parse_args(argv)))


def download(ref: str) -> list[Gcode]:
    """The codes of a MonacoTokens version that are not deprecated, in its order."""
    with urllib.request.urlopen(URL.format(ref=ref), timeout=60) as response:
        entries = cast(list[dict[str, object]], json.load(response))
    return [Gcode(str(e['code']), str(e['summary'])) for e in entries if not e.get('deprecated')]


def write_table(gcodes: list[Gcode], ref: str) -> None:
    """Replace the rows of the table of codes."""
    text = TABLE.read_text(encoding='utf-8')
    rows = f'\t\t  // Generated by scripts/generate_gcodes.py from MonacoTokens {ref}\n'
    rows += ''.join(f'\t\t  {{"{g.code}", "{SECTION}.{g.key}"}},\n' for g in gcodes)
    text, found = TABLE_RE.subn(lambda m: m['start'] + rows + m['end'], text)
    if found != 1:
        sys.exit(f'{TABLE} has no table of codes where it is expected')
    TABLE.write_text(text, encoding='utf-8')


def write_translations(gcodes: list[Gcode]) -> None:
    """Replace the gcodes block of every translation file. A language keeps its own summary of a code,
    one that differs from the English one it replaces."""
    english = cast(dict[str, str], jsonc.load(jsonc.I18N / f'{jsonc.REFERENCE_LANGUAGE}.json')
                   ['translations'].get(SECTION, {}))
    for path in sorted(jsonc.I18N.glob('*.json')):
        own = cast(dict[str, str], jsonc.load(path)['translations'].get(SECTION, {}))
        translated = {k: v for k, v in own.items() if path.stem != jsonc.REFERENCE_LANGUAGE and v != english.get(k)}
        text = path.read_text(encoding='utf-8')
        match = BLOCK_RE.search(text)
        if match is None:
            sys.exit(f'{path} has no {SECTION} block where it is expected')
        indent = match['indent'] + '  '
        entries = ',\n'.join(f'{indent}{json.dumps(g.key)}: {json.dumps(translated.get(g.key, g.summary), ensure_ascii=False)}'
                             for g in gcodes)
        path.write_text(text[:match.start('entries')] + entries + text[match.end('entries'):], encoding='utf-8')
        print(f'{path.name}: {len(gcodes)} codes, {sum(1 for g in gcodes if g.key in translated)} translated')


def main() -> int:
    """Update the table and the translations."""
    options = parse_options(sys.argv[1:])
    gcodes = download(options.ref)
    write_table(gcodes, options.ref)
    write_translations(gcodes)
    print(f'{TABLE.relative_to(ROOT)}: {len(gcodes)} codes from MonacoTokens {options.ref}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
