def emit_derived_header_if_missing(class_base_name: str) -> Optional[str]:
    """Return text for a thin derived header if it does not already exist, else None."""
    # Do not mark with AUTO-GENERATED marker; this is intended for manual overrides later.
    lines: List[str] = []
    lines.append("#pragma once")
    lines.append("")
    lines.append(f"#include \"UI/Lvgl/generated/{class_base_name}.gen.h\"")
    lines.append("")
    lines.append("namespace UI")
    lines.append("{")
    lines.append(f"    class {class_base_name} : public {class_base_name}Gen")
    lines.append("    {")
    lines.append("      public:")
    # Inherit constructors from generated base for convenience
    lines.append(f"        using {class_base_name}Gen::{class_base_name}Gen;")
    lines.append("    };")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def write_if_allowed(path: Path, content: str, force_overwrite: bool) -> bool:
    if path.exists():
        existing = path.read_text(encoding="utf-8", errors="ignore")
        if not force_overwrite and MARKER not in existing:
            # Manual file; don't overwrite unless forced
            return False
        if existing == content:
            return False
    path.write_text(content, encoding="utf-8")
    return True


def ensure_parent_references_generated() -> None:
    """Ensure parent LVGL CMakeLists.txt adds the generated subdirectory."""
    try:
        if not CMAKE_FILE.exists():
            return
        cm = CMAKE_FILE.read_text(encoding="utf-8")
        if re.search(r"^\s*add_subdirectory\(\s*generated\s*\)", cm, re.M):
            return
        updated = "add_subdirectory(generated)\n\n" + cm
        CMAKE_FILE.write_text(updated, encoding="utf-8")
    except Exception:
        pass


def update_generated_cmake(new_gen_cpp_files: List[str]) -> None:
    """
    Maintain src/UI/Lvgl/generated/CMakeLists.txt with the list of generated sources.
    Entries should be of the form: ${CMAKE_CURRENT_SOURCE_DIR}/Lv<Widget>.gen.cpp
    """
    # Normalize to basenames within generated dir
    new_files = [Path(p).name for p in new_gen_cpp_files]
    header = """target_sources(
  DuetScreen.lib
  PRIVATE
"""
    footer = ")\n"
    # Sort unique list
    merged = sorted(set(new_files), key=lambda s: s.lower())
    body_lines = [f"  ${{CMAKE_CURRENT_SOURCE_DIR}}/{fname}" for fname in merged]
    content = header + "\n".join(body_lines) + "\n" + footer
    if not GEN_CMAKE_FILE.exists() or GEN_CMAKE_FILE.read_text(encoding="utf-8") != content:
        GEN_CMAKE_FILE.write_text(content, encoding="utf-8")


def run_clang_format(files: List[Path]) -> None:
    """Run clang-format -i on the provided files if clang-format is available."""
    if not files:
        return
    clang = shutil.which("clang-format")
    if not clang:
        print("[fmt] clang-format not found in PATH; skipping formatting")
        return
    # Deduplicate and ensure absolute paths
    unique_files = []
    seen = set()
    for f in files:
        p = str(Path(f).resolve())
        if p not in seen:
            seen.add(p)
            unique_files.append(p)
    try:
        # Run in chunks to avoid command line limits
        chunk = 100
        for i in range(0, len(unique_files), chunk):
            sub = unique_files[i : i + chunk]
            subprocess.run([clang, "-i", *sub], check=False)
        print(f"[fmt] clang-format applied to {len(unique_files)} files")
    except Exception as e:
        print(f"[fmt] clang-format failed: {e}")


def discover_widget_headers() -> Dict[str, Path]:
    widgets: Dict[str, Path] = {}
    for hdr in WIDGETS_DIR.rglob("lv_*.h"):
        name = hdr.stem  # lv_chart
        if not name.startswith("lv_"):
            continue
        token = name[3:]
        widgets[token] = hdr
    return widgets


def main() -> None:
    ap = argparse.ArgumentParser(description="Generate LVGL C++ wrappers")
    ap.add_argument("--all", action="store_true", help="Generate for all discovered widgets")
    ap.add_argument("--widget", help="Single widget token (e.g., chart)")
    ap.add_argument("--widgets", help="Comma-separated widget tokens")
    ap.add_argument("--map", help="Comma-separated explicit name mappings token:Class (e.g., buttonmatrix:ButtonMatrix)")
    ap.add_argument("--force-overwrite", action="store_true", help="Overwrite existing files, even manual ones")
    args = ap.parse_args()

    mappings: Dict[str, str] = {}
    if args.map:
        for item in args.map.split(','):
            if not item:
                continue
            token, cls = item.split(':', 1)
            mappings[token.strip()] = cls.strip()

    discovered = discover_widget_headers()

    selected: List[str] = []
    if args.all:
        selected = sorted(discovered.keys())
    elif args.widget:
        selected = [args.widget]
    elif args.widgets:
        selected = [s.strip() for s in args.widgets.split(',') if s.strip()]
    else:
        ap.error("Provide --all or --widget or --widgets")

    # Ensure generated output directory exists
    OUTPUT_GEN_DIR.mkdir(parents=True, exist_ok=True)

    generated_cpp: List[str] = []
    generated_files_for_format: List[Path] = []

    for token in selected:
        hdr = discovered.get(token)
        if not hdr:
            print(f"[skip] No header found for widget '{token}'")
            continue
        protos = parse_prototypes(hdr, token)
        methods = build_methods(token, protos)
        if not methods:
            print(f"[skip] No methods found for '{token}'")
            continue
        class_base = f"Lv{mappings.get(token, to_pascal(token))}"
        class_gen = f"{class_base}Gen"

        base_widget = discover_widget_base(token)

        header_text = emit_header_gen(class_base, class_gen, token, methods, base_widget)
        # source_text = emit_source_gen()

        # Generated paths
        gen_h_rel = f"generated/{class_base}.gen.h"
        gen_cpp_rel = None
        gen_h_path = OUTPUT_DIR / gen_h_rel

        wrote_h = write_if_allowed(gen_h_path, header_text, args.force_overwrite)
        wrote_cpp = False

        if wrote_h:
            print(f"[gen] {class_gen} -> {gen_h_rel}")
            generated_files_for_format.append(gen_h_path)
        else:
            print(f"[keep] {gen_h_rel} (existing)")

        # We no longer generate .gen.cpp files (constructor is inline)

        # Create thin derived header if not present
        derived_h_path = OUTPUT_DIR / f"{class_base}.h"
        if not derived_h_path.exists():
            derived_text = emit_derived_header_if_missing(class_base)
            if derived_text:
                derived_h_path.write_text(derived_text, encoding="utf-8")
                print(f"[gen] {class_base} -> {class_base}.h (derived)")
        else:
            print(f"[keep] {class_base}.h (existing)")

    # Ensure parent refers to generated subdir and update its CMake file
    ensure_parent_references_generated()
    update_generated_cmake(generated_cpp)
    # Format generated files
    run_clang_format(generated_files_for_format)


if __name__ == "__main__":
    main()
