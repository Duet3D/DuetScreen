#!/usr/bin/env python3
"""
Generate/update C++ LVGL wrapper classes from LVGL widget headers.

- Scans `libraries/lvgl/src/widgets/**/lv_*.h` for widgets
- Parses function prototypes prefixed with the widget name (e.g., lv_chart_*())
- Emits generated wrappers into `src/UI/Lvgl/generated/` as `Lv<Widget>.gen.h/.gen.cpp`
- Generated class names are suffixed with `Gen` (e.g., `LvLabelGen`)
- Also creates a thin non-generated header `src/UI/Lvgl/Lv<Widget>.h` if missing,
    defining `class Lv<Widget> : public Lv<Widget>Gen` with inherited constructors for manual overrides
- Updates `src/UI/Lvgl/CMakeLists.txt` to include new generated `.gen.cpp` files

Usage:
    python scripts/generate_lvgl_wrappers.py --all
    python scripts/generate_lvgl_wrappers.py --widget chart
    python scripts/generate_lvgl_wrappers.py --widgets chart,table,roller

Notes:
- Naming heuristic uses PascalCase of the widget token: 'chart' -> 'Chart', 'imgbtn' -> 'Imgbtn', 'buttonmatrix' -> 'Buttonmatrix'.
    You can provide explicit mappings via --map buttonmatrix:ButtonMatrix,imgbtn:ImgBtn if desired.
- Only functions whose first parameter is `lv_obj_t*` (or const) are wrapped as methods.
- Methods with names starting with get_/is_/has_ are marked const.
- If a function has a parameter of type `lv_anim_enable_t`, a default of LV_ANIM_ON is provided in the header.

This script aims to generate consistent wrappers matching local style, while being conservative with existing manual files.
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path
import subprocess
import shutil
from datetime import datetime
from typing import List, Tuple, Dict, Optional

ROOT = Path(__file__).resolve().parents[1]
WIDGETS_DIR = ROOT / "libraries" / "lvgl" / "src" / "widgets"
OUTPUT_DIR = ROOT / "src" / "UI" / "Lvgl"
OUTPUT_GEN_DIR = OUTPUT_DIR / "generated"
GEN_CMAKE_FILE = OUTPUT_GEN_DIR / "CMakeLists.txt"
CMAKE_FILE = OUTPUT_DIR / "CMakeLists.txt"
MARKER = "// AUTO-GENERATED BY generate_lvgl_wrappers.py -- DO NOT EDIT"

# Prototype matcher with optional preceding Doxygen comment and optional attributes after args
PROTO_WITH_DOC_RE = re.compile(
    r"(?P<doc>/\*\*.*?\*/)?\s*"  # optional /** ... */
    r"(?P<ret>[\w\s\*]+?)\s+"
    r"(?P<name>lv_([a-z0-9]+)_([A-Za-z0-9_]+))\s*"
    r"\((?P<args>[^)]*)\)\s*"
    r"(?:[A-Za-z_][^;]*)?;",
    re.S,
)
COMMENT_BLOCK_RE = re.compile(r"/\*.*?\*/", re.S)
COMMENT_LINE_RE = re.compile(r"//.*?$", re.M)
WS_RE = re.compile(r"\s+")

# C functions we should not emit as methods
EXCLUDE_SUFFIXES = {
    "create",  # handled by constructor
}

GETTER_PREFIXES = ("get_", "is_", "has_")


def strip_comments(text: str) -> str:
    text = COMMENT_BLOCK_RE.sub("\n", text)
    text = COMMENT_LINE_RE.sub("", text)
    return text


def to_pascal(s: str) -> str:
    # Basic PascalCase: split on underscores, uppercase first char of each token
    parts = s.replace("-", "_").split("_")
    return "".join(p[:1].upper() + p[1:] for p in parts if p)


def to_camel(s: str) -> str:
    parts = s.split("_")
    if not parts:
        return s
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def sanitize_doc(doc: str) -> str:
    """
    Remove C-API-specific lines from the Doxygen block that do not apply to wrappers.
    - Drop any "@param obj" lines, since the wrapper uses 'this' instead of an obj parameter.
    """
    if not doc:
        return doc
    lines = doc.splitlines()
    out: List[str] = []
    for ln in lines:
        # Remove lines like " * @param obj ..." with any spacing variations
        if re.search(r"\*\s*@param\s+obj\b", ln):
            continue
        out.append(ln)
    return "\n".join(out)


def get_lvgl_version() -> str:
    """Parse libraries/lvgl/lv_version.h to build a version string."""
    ver_file = ROOT / "libraries" / "lvgl" / "lv_version.h"
    major = minor = patch = None
    info = None
    try:
        txt = ver_file.read_text(encoding="utf-8")
        m = re.search(r"#define\s+LVGL_VERSION_MAJOR\s+(\d+)", txt)
        if m:
            major = m.group(1)
        m = re.search(r"#define\s+LVGL_VERSION_MINOR\s+(\d+)", txt)
        if m:
            minor = m.group(1)
        m = re.search(r"#define\s+LVGL_VERSION_PATCH\s+(\d+)", txt)
        if m:
            patch = m.group(1)
        m = re.search(r"#define\s+LVGL_VERSION_INFO\s+\"([^\"]*)\"", txt)
        if m:
            info = m.group(1)
    except Exception:
        pass
    if major and minor and patch:
        base = f"{major}.{minor}.{patch}"
    else:
        base = "unknown"
    if info and info.strip():
        return f"{base}-{info.strip()}"
    return base


def banner_lines(filename: str) -> List[str]:
    ts = datetime.now().isoformat(timespec="seconds")
    ver = get_lvgl_version()
    return [
        "/*",
        f" * {filename}",
        " *",
        f" *  AUTO-GENERATED: {ts} by scripts/generate_lvgl_wrappers.py",
        f" *  LVGL version: {ver}",
        " */",
        "",
    ]


def _active_macros_at_pos(text: str, pos: int) -> List[str]:
    """Return a list of active positive macros (e.g., LV_USE_TRANSLATION) at given position."""
    macros_stack: List[str] = []
    cur = 0
    for line in text.splitlines(True):
        ln = line.strip()
        # Handle entering guards
        m = re.match(r"#\s*ifdef\s+(\w+)", ln)
        if not m:
            m = re.match(r"#\s*if\s+defined\s*\(\s*(\w+)\s*\)", ln)
        if not m:
            m = re.match(r"#\s*if\s+(\w+)", ln)
        if m:
            macros_stack.append(m.group(1))
        elif re.match(r"#\s*endif\b", ln):
            if macros_stack:
                macros_stack.pop()
        # We ignore #else/#elif for now
        cur += len(line)
        if cur > pos:
            break
    # Only keep LVGL-style feature macros
    return [mac for mac in macros_stack if mac.startswith("LV_")]


def parse_prototypes(header_path: Path, widget_token: str) -> List[Tuple[str, str, str, str, List[Tuple[str, str, bool]], Optional[str], List[str]]]:
    """
    Return list of (ret_type, full_c_name, suffix, args_str, args[(type,name),...], docstr)
    for functions lv_<widget>_<suffix>();
    """
    raw = header_path.read_text(encoding="utf-8", errors="ignore")

    out = []
    for m in PROTO_WITH_DOC_RE.finditer(raw):
        doc = m.group('doc') or None
        ret_type = WS_RE.sub(" ", (m.group('ret') or '').strip())
        full_name = (m.group('name') or '').strip()
        name_match = re.match(r"lv_([a-z0-9]+)_([A-Za-z0-9_]+)", full_name)
        if not name_match:
            continue
        widget = name_match.group(1)
        suffix = name_match.group(2)
        args_raw = (m.group('args') or '').strip()
        args_str = WS_RE.sub(" ", re.sub(r"\s*\n\s*", " ", args_raw))
        if widget != widget_token:
            continue
        if suffix in EXCLUDE_SUFFIXES:
            continue
        # Determine active macros (guards) at the prototype's position
        guards = _active_macros_at_pos(raw, m.start())
        # parse args into list of (type, name)
        args: List[Tuple[str, str, bool]] = []  # (type, name, is_array)
        if args_raw and args_raw.strip() and args_raw.strip() != "void":
            for param in [p.strip() for p in args_raw.split(',') if p.strip()]:
                if param == '...':
                    args.append(('...', '', False))
                    continue
                if " " in param:
                    t, n = param.rsplit(" ", 1)
                    t_clean = WS_RE.sub(" ", t.strip())
                    is_array = '[' in n and ']' in n
                    n_clean = re.sub(r"\[.*\]", "", n.strip())
                    args.append((t_clean, n_clean, is_array))
                else:
                    args.append((param, f"arg{len(args)+1}", False))
        out.append((ret_type, full_name, suffix, args_str, args, doc, guards))
    return out


def first_param_is_lv_obj(args: List[Tuple[str, str]]) -> bool:
    if not args:
        return False
    t0 = args[0][0].strip()
    return re.match(r"^(?:const\s+)?lv_obj_t\s*\*", t0) is not None


