class MethodMeta:
    def __init__(self, ret_type: str, full_c: str, suffix: str, args: List[Tuple[str, str, bool]]):
        self.ret_type = ret_type.strip()
        self.full_c = full_c
        self.suffix = suffix
        self.args = args  # list of (type,name,is_array)
        self.name = to_camel(suffix)
        self.is_const = self.name.startswith("get") or self.name.startswith("is") or self.name.startswith("has")
        self.has_varargs = any(t.strip() == "..." for (t, _, _) in args)
        self.vfmt_full = None  # optional: C symbol for vfmt counterpart
        self.guards: List[str] = []
        # Map array index -> count index when pattern matches (e.g., size/count)
        self.array_count_pairs: Dict[int, int] = {}
        # Determine if return type is a C string pointer (kept for info only)
        self.ret_is_cstring = re.match(r"^(?:const\s+)?char\s*\*\s*$", self.ret_type) is not None

        # Detect array + count param patterns
        for i in range(1, len(self.args)):
            t_i, n_i, is_arr = self.args[i]
            if not is_arr:
                continue
            j = i + 1
            if j < len(self.args):
                t_j, n_j, _ = self.args[j]
                if re.match(r"^(size_t|uint32_t|int32_t)$", t_j) and re.search(r"(num|count|cnt|size|len)$", n_j):
                    self.array_count_pairs[i] = j

    def _is_cstring(self, t: str, is_arr: bool) -> bool:
        t_s = t.strip()
        if is_arr:
            # Arrays of strings handled via span<const char*>
            return False
        # Exactly one pointer to char and const-qualified
        return ("char" in t_s and t_s.count('*') == 1 and re.match(r"^const\s+?char\s*\*", t_s) is not None)

    def ret_type_cpp(self) -> str:
        """Return the wrapper return type (no C-string conversions)."""
        return self.ret_type

    def decl_args_str(self) -> str:
        items = []
        for idx in range(1, len(self.args)):
            (t, n, is_arr) = self.args[idx]
            t_s = t.strip()
            if t_s == "...":
                items.append("...")
                continue
            # Convert array+count into std::span where possible
            if is_arr:
                elem_t = t_s  # element type for span (e.g., const char*)
                items.append(f"std::span<{elem_t}> {n}")
                # Skip adding the count parameter in declaration if paired
                if idx in self.array_count_pairs:
                    continue
                continue
            # Skip count parameter if it pairs with previous array
            prev_idx = idx - 1
            if prev_idx in self.array_count_pairs and self.array_count_pairs.get(prev_idx) == idx:
                continue
            if t_s == "lv_anim_enable_t":
                items.append(f"{t} {n} = LV_ANIM_ON")
            else:
                items.append(f"{t} {n}")
        return ", ".join(items)

    def impl_args_str(self) -> str:
        """
        Args string for source definitions: no default values.
        Default arguments belong only in the declaration (header).
        """
        items = []
        for idx in range(1, len(self.args)):
            (t, n, is_arr) = self.args[idx]
            t_s = t.strip()
            if t_s == "...":
                items.append("...")
                continue
            if is_arr and idx in self.array_count_pairs:
                elem_t = t_s
                items.append(f"std::span<{elem_t}> {n}")
                continue
            # Skip count parameter if it pairs with previous array
            prev_idx = idx - 1
            if prev_idx in self.array_count_pairs and self.array_count_pairs.get(prev_idx) == idx:
                continue
            if is_arr:
                elem_t = t_s
                items.append(f"std::span<{elem_t}> {n}")
                continue
            items.append(f"{t} {n}")
        return ", ".join(items)

    def call_args_str(self) -> str:
        call_parts = []
        # Iterate preserving original C argument order
        for idx in range(1, len(self.args)):
            (t, n, is_arr) = self.args[idx]
            if t.strip() == "...":
                continue
            # If this is array with paired count, pass data() here
            if is_arr:
                call_parts.append(f"{n}.data()")
                # Count parameter will be handled by following branch
                continue
            # If this is the count that pairs with previous array, pass span.size()
            prev_idx = idx - 1
            if prev_idx in self.array_count_pairs and self.array_count_pairs.get(prev_idx) == idx:
                prev_name = self.args[prev_idx][1]
                call_parts.append(f"{prev_name}.size()")
                continue
            call_parts.append(n)
        return ", ".join(call_parts)


def build_methods(widget_token: str, protos: List[Tuple[str, str, str, str, List[Tuple[str, str, bool]], Optional[str], List[str]]]) -> List[MethodMeta]:
    methods: List[MethodMeta] = []
    # Map suffix -> proto for lookup (e.g., find _vfmt counterpart)
    proto_by_suffix: Dict[str, Tuple[str, str, str, str, List[Tuple[str, str, bool]], Optional[str], List[str]]] = {}
    for p in protos:
        proto_by_suffix[p[2]] = p
    for ret_type, full_c, suffix, _args_str, args, doc, guards in protos:
        if suffix in EXCLUDE_SUFFIXES:
            continue
        if not first_param_is_lv_obj([(t, n) for (t, n, _) in args]):
            continue
        mm = MethodMeta(ret_type, full_c, suffix, args)
        mm.doc = doc
        mm.guards = guards
        # If this method uses varargs, prefer a vfmt counterpart when available; else skip
        if mm.has_varargs:
            # Heuristic: if suffix ends with '_fmt', look for '_vfmt' variant taking va_list
            if suffix.endswith("_fmt"):
                vfmt_suffix = suffix[:-4] + "_vfmt"
                vproto = proto_by_suffix.get(vfmt_suffix)
                if vproto:
                    # confirm last arg is va_list
                    vargs = vproto[4]
                    if any(t.strip().endswith("va_list") for (t, _, _) in vargs):
                        mm.vfmt_full = vproto[1]
                        # keep method; we'll generate wrapper using va_list and call vfmt
                    else:
                        # no va_list variant, skip
                        continue
                else:
                    # no vfmt counterpart; skip varargs method
                    continue
            else:
                # unknown varargs without vfmt; skip
                continue
        methods.append(mm)
    return methods


def _find_widget_c_file(widget_token: str) -> Optional[Path]:
    """Locate the LVGL C implementation file for a widget token (lv_<token>.c)."""
    for cfile in (ROOT / "libraries" / "lvgl" / "src").rglob(f"lv_{widget_token}.c"):
        return cfile
    # Some widgets may live under subfolders with different naming; attempt a broader search
    for cfile in (ROOT / "libraries" / "lvgl" / "src").rglob(f"**/*{widget_token}*.c"):
        if cfile.name == f"lv_{widget_token}.c":
            return cfile
    return None


def discover_widget_base(widget_token: str) -> Optional[str]:
    """
    Parse the widget's C file to discover its base class token via
    `.base_class = &lv_<base>_class`. Returns the base token (e.g., 'image')
    or None if not found or base is lv_obj_class.
    """
    cfile = _find_widget_c_file(widget_token)
    if not cfile or not cfile.exists():
        return None
    try:
        txt = cfile.read_text(encoding="utf-8", errors="ignore")
    except Exception:
        return None
    # Simple, robust scan: locate 'lv_<token>_class', then search for '.base_class = &lv_<base>_class'
    anchor = f"lv_{widget_token}_class"
    idx = txt.find(anchor)
    if idx < 0:
        return None
    window = txt[idx: idx + 4000]  # scan ahead within reasonable window
    m = re.search(r"\.base_class\s*=\s*&lv_([a-z0-9]+)_class", window)
    if not m:
        return None
    base = m.group(1)
    if base == "obj":
        return None
    return base


def emit_header_gen(
    class_base_name: str,
    class_gen_name: str,
    widget_token: str,
    methods: List[MethodMeta],
    base_widget_token: Optional[str],
) -> str:
    lines: List[str] = []
    lines.extend(banner_lines(f"{class_base_name}.gen.h"))
    lines.append("#pragma once")
    lines.append("")
    lines.append("#include \"UI/Lvgl/LvObj.h\"")
    # Include <span> if any method uses std::span
    if any(m.array_count_pairs or any(is_arr for (_, _, is_arr) in m.args[1:]) for m in methods):
        lines.append("#include <span>")
    # No std::string or string_view conversions; keep only <span> if needed
    # If any method uses varargs, include <cstdarg> for va_list usage in header (templates must be header-only)
    if any(m.has_varargs for m in methods):
        lines.append("#include <cstdarg>")
    lines.append("")
    # Emit base include (outside namespace) if inheriting MethodsGen from a base widget
    base_methods_tmpl = None
    if base_widget_token:
        base_class_base = f"Lv{to_pascal(base_widget_token)}"
        lines.append(f"#include \"UI/Lvgl/generated/{base_class_base}.gen.h\"")
        lines.append("")

    lines.append("namespace UI")
    lines.append("{")
    lines.append(f"    {MARKER}")
    # Determine class-wide guards present on all methods
    if methods:
        class_guards = sorted(set.intersection(*(set(m.guards) for m in methods)))
    else:
        class_guards = []

    if class_guards:
        lines.append("")
    for g in class_guards:
        lines.append(f"    #if {g}")
    if class_guards:
        lines.append("")

    # Forward declare the public non-generated class so we can reference it as the Derived parameter
    lines.append(f"    class {class_base_name};")
    lines.append("")

    # Emit MethodsGen template, inheriting from base widget's MethodsGen if available
    if base_widget_token:
        base_methods_tmpl = f"Lv{to_pascal(base_widget_token)}MethodsGen<Derived>"

    inherit_clause = f" : public {base_methods_tmpl}" if base_methods_tmpl else ""
    lines.append(f"    template <typename Derived>")
    lines.append(f"    class {class_base_name}MethodsGen{inherit_clause}")
    lines.append("    {")
    lines.append("      public:")

    # Stream inline methods inside template, with per-method guards
    active_method_guards: List[str] = []
    for m in methods:
        extra_guards = [g for g in m.guards if g not in class_guards]
        if active_method_guards != extra_guards:
            for _ in reversed(active_method_guards):
                lines.append("        #endif")
            if active_method_guards:
                lines.append("")
            for g in extra_guards:
                lines.append(f"        #if {g}")
            if extra_guards:
                lines.append("")
            active_method_guards = extra_guards
        if getattr(m, 'doc', None):
            for dl in sanitize_doc(m.doc).splitlines():
                lines.append("        " + dl)
        const_str = " const" if m.is_const else ""
        # Emit inline body calling C API with UI_LOCK
        lines.append(
            f"        {m.ret_type_cpp()} {m.name}({m.decl_args_str()}){const_str} requires HasGetRootPtr<Derived>")
        lines.append("        {")
        lines.append("            ZoneScoped;")
        lines.append("            UI_LOCK();")
        root_expr = ("static_cast<const Derived*>(this)->getRootPtr()" if m.is_const else
                     "static_cast<Derived*>(this)->getRootPtr()")
        if m.ret_type.strip() == "void":
            if m.has_varargs and m.vfmt_full:
                fmt_name = None
                for (t, n, _) in m.args[::-1]:
                    if t.strip() == "...":
                        continue
                    if n:
                        fmt_name = n
                        break
                if fmt_name is None:
                    fmt_name = "fmt"
                lines.append("            va_list args;")
                lines.append(f"            va_start(args, {fmt_name});")
                call_args = ", ".join([
                    root_expr,
                    fmt_name,
                    "args",
                ])
                lines.append(f"            {m.vfmt_full}({call_args});")
                lines.append("            va_end(args);")
            else:
                call_args = ", ".join([
                    root_expr,
                    m.call_args_str(),
                ]) if m.call_args_str() else root_expr
                lines.append(f"            {m.full_c}({call_args});")
            lines.append("        }")
            lines.append("")
        else:
            call_args = ", ".join([
                root_expr,
                m.call_args_str(),
            ]) if m.call_args_str() else root_expr
            lines.append("            return " + f"{m.full_c}({call_args});")
            lines.append("        }")
            lines.append("")

    for _ in reversed(active_method_guards):
        lines.append("        #endif")

    lines.append("    };")
    lines.append("")

    # Emit the generated concrete class inheriting LvObj and MethodsGen specialized on the public class
    lines.append(f"    class {class_gen_name} : public LvObj, public {class_base_name}MethodsGen<{class_base_name}>")
    lines.append("    {")
    lines.append("      public:")
    lines.append(f"        {class_gen_name}(const std::string& name, LvObj& parent)")
    lines.append(f"            : LvObj(lv_{widget_token}_create, name, parent)")
    lines.append("        {")
    lines.append("            ZoneScoped;")
    lines.append("            UI_LOCK();")
    lines.append("        }")
    lines.append("    };")

    if class_guards:
        lines.append("")
    for _ in reversed(class_guards):
        lines.append("    #endif")
    if class_guards:
        lines.append("")
    lines.append("} // namespace UI")
    lines.append("")
    return "\n".join(lines)


